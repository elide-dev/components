// Regenerates build-time highlighting fixtures for Storybook (Twoslash needs
// Node and TypeScript, so stories use its serialized output).
// Run: bun scripts/generate-code-fixtures.ts
import { writeFileSync } from "node:fs";
import { highlightCode } from "../src/components/shiki";

const twoslashSource = `import { Database } from "elide:sqlite";
// Hover any identifier: types come from Twoslash at build time

interface User { id: number; name: string }

const db = new Database(":memory:");
const user = db.prepare<User>("SELECT * FROM users WHERE id = ?").get(1);
//    ^?
console.log(user.name.toUpperCase()); // [!code highlight]`;

// A minimal ambient module so the sample type-checks without Elide's typings.
const header = `// @filename: elide.d.ts
declare module "elide:sqlite" {
  export class Database {
    constructor(path: string);
    prepare<T>(sql: string): { get(...params: unknown[]): T };
  }
}
// @filename: app.ts
// ---cut---
`;

const result = await highlightCode(header + twoslashSource, "ts", { twoslash: true });
writeFileSync(
  new URL("../src/stories/fixtures/twoslash.ts", import.meta.url),
  `// Generated by scripts/generate-code-fixtures.ts: build-time Shiki + Twoslash output.\n` +
    `import type { HighlightedCode } from "../../components/shiki";\n\n` +
    `export const twoslashSample: HighlightedCode = ${JSON.stringify(result, null, 2)};\n`,
);
console.log(`twoslash fixture: ${result.lines.length} lines, ${result.inline.length} hovers`);
